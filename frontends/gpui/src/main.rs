/// One window model; the whole app. `demo` = scripted-device mode (from
/// the `--demo` flag, :parsing in `main`); it only ever changes
/// presentation (chip/title/footer), never behavior and never the device
/// API surface. The rocker is the window's keyboard control (Space/Enter
/// inside its `key_context`; see `main`), so it owns the FocusHandle.
struct AppModel {
    focus: FocusHandle,
    /// The EQ selector's keyboard handle — its own (separate from the
    /// rocker) so the "eq_selector" context keys (Left/Right) dispatch only
    /// while that well is focused.
    eq_focus: FocusHandle,
    /// The Volume selector's keyboard handle — same rule as `eq_focus`,
    /// its own "volume_selector" key context (Left/Right there step the six
    /// stops, disjoint from the EQ well's bindings).
    volume_focus: FocusHandle,
    /// The Reverb size selector's keyboard handle — same rule as the other
    /// selector wells, its own "reverb_selector" key context (Left/Right
    /// step the three gears while it holds focus).
    reverb_focus: FocusHandle,
    /// The Reverb switch's keyboard handle — its own "reverb_toggle" key
    /// context (Space/Enter flip while the switch wrapper holds focus).
    reverb_toggle_focus: FocusHandle,
    /// The Channel-mode selector's keyboard handle — same rule as the
    /// other selector wells, its own "channel_selector" key context
    /// (Left/Right step the two mode pads while it holds focus).
    channel_focus: FocusHandle,
    /// The Schedule selector's keyboard handle — same rule as the
    /// other selector wells, its own "schedule_selector" key context
    /// (Left/Right step the two timer pads while it holds focus).
    schedule_focus: FocusHandle,
    /// The Indicator-light switch's keyboard handle — its own
    /// "light_toggle" key context (Space/Enter flip while the switch
    /// wrapper holds focus), the same rule as the reverb switch.
    light_toggle_focus: FocusHandle,
    /// The Mic-recognition switch's keyboard handle — its own
    /// "mic_toggle" key context (Space/Enter flip while the switch
    /// wrapper holds focus), the same rule as the light switch.
    mic_toggle_focus: FocusHandle,
    vm: ViewModel,
    device: DeviceHandle,
    demo: Option<DemoScenario>,
}

impl AppModel {
    /// Stream-side entry: replace the VM, repaint. No interpretation here —
    /// pending/banners/errors were already decided by the actor + vm.
    fn apply_snapshot(&mut self, snap: holly_app::Snapshot, cx: &mut Context<Self>) {
        self.vm = view_model(&snap);
        cx.notify();
    }

    /// The toggle's single flip path (Space/Enter/the rocker container);
    /// [`nc_write_accepted`] is the whole gate (nothing in flight, state
    /// verified). The flip target is computed from the VERIFIED state.
    fn toggle_nc(&mut self, _: &ToggleNoise, _: &mut Window, _: &mut Context<Self>) {
        if nc_write_accepted(&self.vm.nc)
            && let Some(state) = self.vm.nc.state
        {
            self.device.set_noise(!state);
        }
    }

    /// One level pick for mouse AND keyboard; [`level_pick`] is the whole
    /// decision (blocked while pending, blocked with the switch off, noop
    /// when already that level).
    fn set_nc_level(&mut self, level: u8, _: &mut Context<Self>) {
        if level_pick(level, &self.vm.nc) == LevelPick::Write {
            self.device.set_noise_level(level);
        }
    }

    fn on_nc_low(&mut self, _: &NcLow, _: &mut Window, cx: &mut Context<Self>) {
        self.set_nc_level(0, cx);
    }

    fn on_nc_medium(&mut self, _: &NcMedium, _: &mut Window, cx: &mut Context<Self>) {
        self.set_nc_level(1, cx);
    }

    fn on_nc_strong(&mut self, _: &NcStrong, _: &mut Window, cx: &mut Context<Self>) {
        self.set_nc_level(2, cx);
    }

    /// A rocker pad click requests THAT pad's state explicitly (pressing
    /// the lit pad is a noop — a rocker, not a toggle): same gate, explicit
    /// request, dedup on the verified state.
    fn request_nc(&mut self, request: bool, _window: &mut Window, _cx: &mut Context<Self>) {
        if nc_write_accepted(&self.vm.nc) && self.vm.nc.state != Some(request) {
            self.device.set_noise(request);
        }
    }

    /// The shared Left/Right stepper for the four context-scoped selectors
    /// (EQ/Volume/Channel/Schedule — reverb keeps its own trio: its cursor
    /// is the gear byte, not `selected`, and no cx rides). With no verified
    /// selection the step is a noop — the VM's `selected` is the only
    /// cursor, matching the "no pending target" rule — and outside
    /// `0..=last` it stops at the edge. `set` is the SAME pick path the
    /// mouse uses (a fn pointer, so the capture-less call-site closures
    /// coerce), keeping mouse and keyboard on one decision
    /// ([`controls::*_pick`]).
    fn step_selection(
        &mut self,
        selected: Option<usize>,
        last: isize,
        step: isize,
        set: fn(&mut AppModel, usize, &mut Context<AppModel>),
        cx: &mut Context<Self>,
    ) {
        if let Some(selected) = selected {
            let next = selected as isize + step;
            if (0..=last).contains(&next) {
                set(self, next as usize, cx);
            }
        }
    }

    /// One EQ pad pick for mouse AND keyboard — [`eq_pick`] is the whole
    /// decision (read-only family or an in-flight EQ write: blocked;
    /// already-selected: noop; else write). The WIRE byte comes from the
    /// VM's tested translation (`eq_pad_wire`) — this file never names a
    /// device pad value.
    fn set_eq_pad(&mut self, index: usize, _: &mut Context<Self>) {
        if eq_pick(index, &self.vm.eq) == EqPick::Write
            && let Some(wire) = eq_pad_wire(index)
        {
            self.device.set_eq(wire);
        }
    }

    /// Left/Right stepping over the pads (the design's arrow-key spec does
    /// not exist — mirroring the rocker's context-scoped keyboard rule;
    /// NC's global 1/2/3 stay untouched). With no verified selection the
    /// step is a noop: the VM's `selected` is the only cursor, matching the
    /// "no pending target" rule.
    fn eq_step(&mut self, step: isize, cx: &mut Context<Self>) {
        self.step_selection(
            self.vm.eq.selected,
            2,
            step,
            |this, index, cx| this.set_eq_pad(index, cx),
            cx,
        );
    }

    fn on_eq_prev(&mut self, _: &EqPrev, _: &mut Window, cx: &mut Context<Self>) {
        self.eq_step(-1, cx);
    }

    fn on_eq_next(&mut self, _: &EqNext, _: &mut Window, cx: &mut Context<Self>) {
        self.eq_step(1, cx);
    }

    /// One Volume-stop pick for mouse AND keyboard — [`volume_pick`] is the
    /// whole decision (read-only family or an in-flight gain write:
    /// blocked; already-selected: noop; else write). The WIRE byte comes
    /// from the VM's tested translation (`volume_pad_wire`) — this file
    /// never names a device stop value.
    fn set_gain_stop(&mut self, index: usize, _: &mut Context<Self>) {
        if volume_pick(index, &self.vm.volume) == VolumePick::Write
            && let Some(wire) = volume_pad_wire(index)
        {
            self.device.set_gain(wire);
        }
    }

    /// Left/Right stepping over the six stops (same context-scoped rule as
    /// the EQ well; the two selectors' bindings are disjoint key contexts).
    /// With no verified selection the step is a noop: the VM's `selected`
    /// is the only cursor, matching the "no pending target" rule.
    fn volume_step(&mut self, step: isize, cx: &mut Context<Self>) {
        self.step_selection(
            self.vm.volume.selected,
            5,
            step,
            |this, index, cx| this.set_gain_stop(index, cx),
            cx,
        );
    }

    fn on_volume_prev(&mut self, _: &VolumePrev, _: &mut Window, cx: &mut Context<Self>) {
        self.volume_step(-1, cx);
    }

    fn on_volume_next(&mut self, _: &VolumeNext, _: &mut Window, cx: &mut Context<Self>) {
        self.volume_step(1, cx);
    }

    /// The reverb toggle's single flip path (Space/Enter via the action,
    /// click via the switch wrapper); [`reverb_toggle_accepted`] is the
    /// whole gate. The flip target is computed from the VERIFIED state; the
    /// device's current gear rides along — the APK's switch handler sends
    /// the remembered `reverbType` (HLDevice6302Activity.java:792-793
    /// [code]), and an unknown gear falls back to the APK's own default
    /// GEAR_ONE(0) (`:341`) — [`reverb_toggle_wire`] is the whole
    /// translation.
    fn flip_reverb(&mut self) {
        if let Some(reverb) = self.vm.reverb.as_ref()
            && reverb_toggle_accepted(reverb)
            && let Some(enabled) = reverb.enabled
        {
            let (switch, gear) = reverb_toggle_wire(!enabled, reverb.gear);
            self.device.set_reverb(switch, gear);
        }
    }

    fn on_toggle_reverb(&mut self, _: &ToggleReverb, _: &mut Window, _: &mut Context<Self>) {
        self.flip_reverb();
    }

    /// The light toggle's single flip path (Space/Enter via the action,
    /// click via the switch wrapper); [`light_toggle_accepted`] is the
    /// whole gate. The flip target is computed from the VERIFIED state;
    /// the WIRE byte comes from the VM's tested inversion
    /// ([`indicator_light_wire`]) — this file never names a device value
    /// (the wire space is INVERTED, 0 = on; both APK sides carry the same
    /// inversion, checklist §3).
    fn flip_light(&mut self) {
        if light_toggle_accepted(&self.vm.light)
            && let Some(on) = self.vm.light.on
        {
            let wire = indicator_light_wire(!on);
            self.device.set_indicator_light(wire);
        }
    }

    fn on_toggle_light(&mut self, _: &ToggleLight, _: &mut Window, _: &mut Context<Self>) {
        self.flip_light();
    }

    /// The mic-recognition toggle's single flip path (Space/Enter via the
    /// action, click via the switch wrapper); [`mic_toggle_accepted`] is
    /// the whole gate. The flip target is computed from the VERIFIED
    /// state; the WIRE byte comes from the VM's tested identity
    /// translation ([`mic_recognition_wire`]) — this file never names a
    /// device value (the space is OFF = 0 / ON = 1 on both sides,
    /// checklist §3).
    fn flip_mic_recognition(&mut self) {
        if mic_toggle_accepted(&self.vm)
            && let Some(on) = self.vm.mic_recognition.on
        {
            let wire = mic_recognition_wire(!on);
            self.device.set_mic_recognition(wire);
        }
    }

    fn on_toggle_mic_recognition(
        &mut self,
        _: &ToggleMicRecognition,
        _: &mut Window,
        _: &mut Context<Self>,
    ) {
        self.flip_mic_recognition();
    }

    /// One reverb gear pick for mouse AND keyboard — [`reverb_pick`] is the
    /// whole decision (read-only family / in-flight write / unverified
    /// switch: blocked; the ON device's own gear: noop; else write). The
    /// WIRE pair is (switch on, the picked gear) — the APK's gear buttons
    /// (`HLDevice6302Activity.java:759/:769/:779` [code]); the byte comes
    /// from the VM's tested translation ([`reverb_gear_wire`]) — this file
    /// never names a device gear value.
    fn set_reverb_gear(&mut self, index: usize) {
        if let Some(reverb) = self.vm.reverb.as_ref()
            && reverb_pick(index, reverb) == ReverbPick::Write
            && let Some(wire) = reverb_gear_wire(index)
        {
            self.device.set_reverb(true, wire);
        }
    }

    /// Left/Right stepping over the three gears (same context-scoped rule
    /// as the EQ/Volume wells; NC's global 1/2/3 stay untouched). With no
    /// verified selection the step is a noop: the VM's gear is the only
    /// cursor, matching the "no pending target" rule.
    fn reverb_step(&mut self, step: isize) {
        if let Some(gear) = self.vm.reverb.as_ref().and_then(|r| r.gear) {
            let next = gear as isize + step;
            if (0..=2).contains(&next) {
                self.set_reverb_gear(next as usize);
            }
        }
    }

    fn on_reverb_prev(&mut self, _: &ReverbPrev, _: &mut Window, _: &mut Context<Self>) {
        self.reverb_step(-1);
    }

    fn on_reverb_next(&mut self, _: &ReverbNext, _: &mut Window, _: &mut Context<Self>) {
        self.reverb_step(1);
    }

    /// One Channel-mode pick for mouse AND keyboard — [`channel_pick`] is
    /// the whole decision (read-only family or an in-flight channel-mode
    /// write: blocked; already-selected: noop; else write). The WIRE byte
    /// comes from the VM's tested translation (`channel_mode_pad_wire`) —
    /// this file never names a device value.
    fn set_channel_mode(&mut self, index: usize, _: &mut Context<Self>) {
        if channel_pick(index, &self.vm.channel_mode) == ChannelPick::Write
            && let Some(wire) = channel_mode_pad_wire(index)
        {
            self.device.set_channel_mode(wire);
        }
    }

    /// Left/Right stepping over the two mode pads (same context-scoped
    /// rule as the EQ/Volume/reverb wells; NC's global 1/2/3 stay
    /// untouched). With no verified selection the step is a noop: the
    /// VM's `selected` is the only cursor, matching the "no pending
    /// target" rule.
    fn channel_step(&mut self, step: isize, cx: &mut Context<Self>) {
        self.step_selection(
            self.vm.channel_mode.selected,
            1,
            step,
            |this, index, cx| this.set_channel_mode(index, cx),
            cx,
        );
    }

    fn on_channel_prev(&mut self, _: &ChannelPrev, _: &mut Window, cx: &mut Context<Self>) {
        self.channel_step(-1, cx);
    }

    fn on_channel_next(&mut self, _: &ChannelNext, _: &mut Window, cx: &mut Context<Self>) {
        self.channel_step(1, cx);
    }

    /// One Schedule pick for mouse AND keyboard — [`schedule_pick`] is
    /// the whole decision (read-only family or an in-flight
    /// shutdown-timer write: blocked; already-selected: noop; else
    /// write). The WIRE byte comes from the VM's tested translation
    /// (`shutdown_pad_wire`) — this file never names a device value.
    /// ⚠ semantic difference from the other pickers: BOTH timer values
    /// are device actions (Never = disarm, 15min = arm the countdown);
    /// there is no third value and none may be invented — the VM's
    /// `Option` returns None outside 0..=1 and the pick simply never
    /// fires.
    fn set_schedule_power_off(&mut self, index: usize, _: &mut Context<Self>) {
        if schedule_pick(index, &self.vm.shutdown) == SchedulePick::Write
            && let Some(wire) = shutdown_pad_wire(index)
        {
            self.device.set_schedule_power_off(wire);
        }
    }

    /// Left/Right stepping over the two timer pads (same context-scoped
    /// rule as the EQ/Volume/reverb/channel wells). With no verified
    /// selection the step is a noop: the VM's `selected` is the only
    /// cursor, matching the "no pending target" rule.
    fn schedule_step(&mut self, step: isize, cx: &mut Context<Self>) {
        self.step_selection(
            self.vm.shutdown.selected,
            1,
            step,
            |this, index, cx| this.set_schedule_power_off(index, cx),
            cx,
        );
    }

    fn on_schedule_prev(&mut self, _: &SchedulePrev, _: &mut Window, cx: &mut Context<Self>) {
        self.schedule_step(-1, cx);
    }

    fn on_schedule_next(&mut self, _: &ScheduleNext, _: &mut Window, cx: &mut Context<Self>) {
        self.schedule_step(1, cx);
    }

    /// One mic card's mute flip path (the chip click; no keyboard action —
    /// the feature spec wires the Mute button for click only).
    /// [`mic_mute_write_accepted`] is the whole gate, and the flip target
    /// is computed from the VERIFIED state (`!muted`) — never optimistically.
    /// The WIRE slot comes from the VM's tested translation
    /// ([`tx_mute_wire`]) — this file never names a device slot value.
    fn flip_mic_mute(&mut self, slot: usize) {
        let tx = match slot {
            0 => self.vm.tx1.as_ref(),
            1 => self.vm.tx2.as_ref(),
            _ => None,
        };
        if let Some(tx) = tx
            && mic_mute_write_accepted(tx)
            && let Some(wire) = tx_mute_wire(slot)
        {
            self.device.set_tx_mute(wire, !tx.muted);
        }
    }

    fn refresh_now(&mut self, _: &mut Context<Self>) {
        self.device.refresh();
    }
}

