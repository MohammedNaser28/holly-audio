/// `--demo [word]`, std-only and testable (no clap in a frontend of this
/// size). The flag may appear anywhere; an optional following word selects
/// the scenario via [`DemoScenario::from_word`] (bare flag = `connected`).
/// An unrecognized flag or word is a USAGE ERROR: print and exit(2) — never
/// a silent fallback to a session the user did not pick. Not directly
/// testable for the exit path (std process exit); tests cover the returned
/// arms.
fn parse_demo_args(args: impl Iterator<Item = String>) -> Option<DemoScenario> {
    let mut saw_flag = false;
    let mut word: Option<String> = None;
    for arg in args {
        if arg == "--demo" {
            saw_flag = true;
        } else if saw_flag && word.is_none() && !arg.starts_with('-') {
            word = Some(arg); // the scenario word right after the flag
        } else {
            eprintln!("usage: holly-gpui [--demo [connected|pending|busy]]");
            eprintln!("unrecognized argument: {arg}");
            std::process::exit(2);
        }
    }
    if !saw_flag {
        return None;
    }
    DemoScenario::from_word(word.as_deref()).inspect(|_| {})
}

/// holly-gpui: the window. Boots the shared actor behind a handle, opens the
/// ONLY window of the app, and pumps the blocking snapshot channel into the
/// executor (a std Receiver cannot be awaited — the bridge lives here, see
/// the module docs and old task-8 notes).
fn main() {
    Application::new()
        .with_assets(IconAssets) // assets ship inside the binary (app.rs:155)
        .run(|cx: &mut App| {
            // T2: register the bundled Hanken Grotesk faces before the first
            // window opens; failure logs once and falls back to the system
            // sans (fonts.rs).
            fonts::register(cx);

            // Keyboard: Space/Enter flip the rocker ONLY while its well is
            // focused (key context "nc_rocker"); 1/2/3 and ctrl-r are global
            // bindings — with nothing focused their actions dispatch at the
            // window ROOT (window.rs:3982-3988), which carries the
            // corresponding on_action listeners. Left/Right step the EQ
            // pads ONLY while the EQ well is focused (key context
            // "eq_selector"), the Volume stops ONLY while the volume
            // well is focused ("volume_selector"), the reverb gears
            // ONLY while the reverb well is focused ("reverb_selector"),
            // the Channel-mode pads ONLY while the channel well is
            // focused ("channel_selector"), and the Schedule pads ONLY
            // while the schedule well is focused ("schedule_selector");
            // Space/Enter flip the reverb switch only inside
            // "reverb_toggle" and the Indicator-light switch only inside
            // "light_toggle" — the design defines no inter-selector
            // arrow keys (no invented global bindings stealing NC's
            // 1/2/3).
            cx.bind_keys([
                KeyBinding::new("space", ToggleNoise, Some("nc_rocker")),
                KeyBinding::new("enter", ToggleNoise, Some("nc_rocker")),
                KeyBinding::new("left", EqPrev, Some("eq_selector")),
                KeyBinding::new("right", EqNext, Some("eq_selector")),
                // Left/Right step the Volume stops ONLY while the volume
                // well is focused ("volume_selector" context) — disjoint
                // from the EQ well's identical keys, no invented global
                // bindings.
                KeyBinding::new("left", VolumePrev, Some("volume_selector")),
                KeyBinding::new("right", VolumeNext, Some("volume_selector")),
                // Space/Enter flip the reverb switch ONLY while the switch
                // wrapper is focused ("reverb_toggle"); Left/Right step the
                // gears ONLY while the selector well is focused
                // ("reverb_selector") — three disjoint selector contexts,
                // no invented global bindings.
                KeyBinding::new("space", ToggleReverb, Some("reverb_toggle")),
                KeyBinding::new("enter", ToggleReverb, Some("reverb_toggle")),
                KeyBinding::new("left", ReverbPrev, Some("reverb_selector")),
                KeyBinding::new("right", ReverbNext, Some("reverb_selector")),
                // Left/Right step the Channel-mode pads ONLY while that
                // well is focused ("channel_selector" context) — four
                // disjoint selector contexts, no invented global bindings.
                KeyBinding::new("left", ChannelPrev, Some("channel_selector")),
                KeyBinding::new("right", ChannelNext, Some("channel_selector")),
                // Left/Right step the Schedule pads ONLY while that well
                // is focused ("schedule_selector" context) — still
                // disjoint, no invented global bindings.
                KeyBinding::new("left", SchedulePrev, Some("schedule_selector")),
                KeyBinding::new("right", ScheduleNext, Some("schedule_selector")),
                // Space/Enter flip the Indicator-light switch ONLY while
                // the switch wrapper is focused ("light_toggle" context) —
                // the same rule as the reverb switch, still disjoint, no
                // invented global bindings.
                KeyBinding::new("space", ToggleLight, Some("light_toggle")),
                KeyBinding::new("enter", ToggleLight, Some("light_toggle")),
                // Space/Enter flip the Mic-recognition switch ONLY while
                // the switch wrapper is focused ("mic_toggle" context) —
                // the same rule as the light switch, still disjoint, no
                // invented global bindings.
                KeyBinding::new("space", ToggleMicRecognition, Some("mic_toggle")),
                KeyBinding::new("enter", ToggleMicRecognition, Some("mic_toggle")),
                KeyBinding::new("1", NcLow, None),
                KeyBinding::new("2", NcMedium, None),
                KeyBinding::new("3", NcStrong, None),
                KeyBinding::new("ctrl-r", Refresh, None),
                KeyBinding::new("ctrl-q", Quit, None),
            ]);
            cx.on_action(|_: &Quit, cx| cx.quit());
            cx.on_window_closed(|cx| {
                if cx.windows().is_empty() {
                    cx.quit();
                }
            })
            .detach();

            // The device actor owns the ONLY claim. `--demo [word]` starts
            // the SAME actor over the scripted DemoDevice (demo.rs): zero
            // USB in demo mode, clearly marked in the UI (chip + title +
            // footer).
            let demo = parse_demo_args(std::env::args().skip(1));
            let device = match demo {
                Some(scenario) => holly_app::demo::start_demo_scenario(scenario),
                None => holly_app::start(),
            };
            let rx = device.subscribe();
            eprintln!("[holly] demo={demo:?} subscribed"); // TEMP-DEBUG

            let window = cx
                .open_window(
                    WindowOptions {
                        window_bounds: Some(WindowBounds::Windowed(Bounds::centered(
                            None,
                            size(
                                px(theme::metrics::WINDOW_DEFAULT_WIDTH),
                                px(theme::metrics::WINDOW_DEFAULT_HEIGHT),
                            ),
                            cx,
                        ))),
                        // The mock's grid (1fr auto 132px 120px) does not
                        // reflow below the designed size — clamp it.
                        window_min_size: Some(size(
                            px(theme::metrics::WINDOW_DEFAULT_WIDTH),
                            px(theme::metrics::WINDOW_DEFAULT_HEIGHT),
                        )),
                        // CSD: `Client` drops the compositor chrome (the
                        // titlebar is drawn in render_titlebar) while
                        // `title`/`appears_transparent` keep the xdg window
                        // name for taskbars — image_gallery.rs:263-271
                        // pattern; fields verified platform.rs:1122-1131.
                        titlebar: Some(TitlebarOptions {
                            title: Some(if demo.is_some() {
                                "HOLLY — DEMO".into()
                            } else {
                                "HOLLY".into()
                            }),
                            appears_transparent: true,
                            ..Default::default() // traffic_light_position (platform.rs:1257), derives Default (platform.rs:1244-1248)
                        }),
                        window_decorations: Some(WindowDecorations::Client),
                        app_id: Some("holly-gpui".to_string()),
                        ..Default::default()
                    },
                    |window, cx| {
                        cx.new(|cx| {
                            // The rocket rocker owns the keyboard on start:
                            // focusing its handle puts "nc_rocker" on the
                            // dispatch path from the first frame
                            // (on_window_close_quit.rs:58 pattern).
                            let focus = cx.focus_handle();
                            focus.focus(window);
                            let eq_focus = cx.focus_handle();
                            let volume_focus = cx.focus_handle();
                            let reverb_focus = cx.focus_handle();
                            let reverb_toggle_focus = cx.focus_handle();
                            let channel_focus = cx.focus_handle();
                            let schedule_focus = cx.focus_handle();
                            let light_toggle_focus = cx.focus_handle();
                            let mic_toggle_focus = cx.focus_handle();
                            AppModel {
                                focus,
                                eq_focus,
                                volume_focus,
                                reverb_focus,
                                reverb_toggle_focus,
                                channel_focus,
                                schedule_focus,
                                light_toggle_focus,
                                mic_toggle_focus,
                                vm: ViewModel::default(),
                                device,
                                demo,
                            }
                        })
                    },
                )
                .unwrap();

            let view: Entity<AppModel> = window.update(cx, |_, _, cx| cx.entity()).unwrap();

            // ---- blocking Receiver -> executor bridge (see module docs) ----
            let (snap_tx, mut snap_rx) = unbounded::<holly_app::Snapshot>();
            thread::Builder::new()
                .name("holly-gpui-pump".to_string())
                .spawn(move || {
                    for snap in rx {
                        eprintln!(
                            "[holly] pump -> {:?} detail={:?} pending={:?}",
                            snap.status, snap.detail, snap.pending_set
                        ); // TEMP-DEBUG
                        if snap_tx.unbounded_send(snap).is_err() {
                            break; // UI side is gone
                        }
                    }
                    // Keep rx alive until UI teardown; rx dropped here
                    // releases our subscriber slot (Hub silently drops
                    // lagged subs).
                })
                .expect("spawn holly-gpui-pump");

            cx.spawn(async move |cx| {
                // snap_rx.next() requires `futures::StreamExt` (import above).
                while let Some(snap) = snap_rx.next().await {
                    eprintln!("[holly] ui <- {:?}", snap.status); // TEMP-DEBUG
                    if view
                        .update(cx, |model, cx| model.apply_snapshot(snap, cx))
                        .is_err()
                    {
                        eprintln!("[holly] ui update FAILED; breaking"); // TEMP-DEBUG
                        break; // view released (window closed)
                    }
                }
            })
            .detach();
        });
}
